# Installs the `aider-local` command for this clone of the repo.
# Run once per PC (and again if you move the repo folder):
#
#   powershell -ExecutionPolicy Bypass -File local-ai\install.ps1
#
# It writes %USERPROFILE%\.local\bin\aider-local.cmd, a one-line shim that runs
# aider-local.ps1 from wherever this repo lives. That folder is where `uv tool install`
# puts aider.exe, so it is normally on PATH already.

$ErrorActionPreference = 'Stop'

$script = Join-Path $PSScriptRoot 'aider-local.ps1'
$binDir = Join-Path $env:USERPROFILE '.local\bin'
$shim = Join-Path $binDir 'aider-local.cmd'

New-Item -ItemType Directory -Force -Path $binDir | Out-Null
$lines = @(
    '@echo off',
    "rem Generated by $PSCommandPath",
    "powershell.exe -NoProfile -ExecutionPolicy Bypass -File `"$script`" %*"
)
# ASCII + CRLF: cmd.exe needs both.
[System.IO.File]::WriteAllText($shim, (($lines -join "`r`n") + "`r`n"), [System.Text.Encoding]::ASCII)
Write-Host "Installed $shim -> $script" -ForegroundColor Green

$onPath = ($env:Path -split ';') | Where-Object { $_.TrimEnd('\') -ieq $binDir }
if (-not $onPath) {
    Write-Host "$binDir is not on PATH. Run 'uv tool update-shell', then open a new terminal." -ForegroundColor Yellow
}
foreach ($tool in 'aider', 'ollama') {
    if (-not (Get-Command $tool -ErrorAction SilentlyContinue) -and
        -not ($tool -eq 'ollama' -and (Test-Path (Join-Path $env:LOCALAPPDATA 'Programs\Ollama\ollama.exe')))) {
        Write-Host "Missing: $tool (see README.md -> 'Set up on another PC')" -ForegroundColor Yellow
    }
}
